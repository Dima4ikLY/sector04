import {defaultBindings,keyLabel} from './keybinds.mjs';

const controls=[
  (touch,key)=>`Удерживай ${touch?'«Гран.»':key('grenade')}, чтобы увидеть траекторию. Отпусти для броска.`,
  (touch,key)=>touch?'Для подката дважды нажми ← или →. Подкат работает и в воздухе.':`Для подката удерживай ${key('left')} или ${key('right')} и нажми ${key('slide')}. Подкат работает и в воздухе.`,
  (touch,key)=>`Нажми ${touch?'«Сальто»':key('flip')} в воздухе. Движение в сторону прицела — сальто вперёд, в обратную — назад. Без направления — вбок.`,
  (touch,key)=>`Перезаряди оружие за укрытием. Нажми ${touch?'«Перез.»':key('reload')}.`,
  ()=> 'Лечись за укрытием. Аптечка замедляет движение на время лечения.'
];

const pickups=[
  'Подобранная аптечка пополняет запас. Используй её, когда получишь урон.',
  'Усиления появляются по одному в разных местах. Аптечки возвращаются на прежние точки.',
  'Критический заряд усиливает следующую пулю и расходуется даже при промахе.',
  'Временная броня принимает часть урона на себя.'
];

const teamTips=[
  'Фраги идут в общий счёт команды.',
  'Займите разные ярусы, чтобы держать в поле зрения больше арены.'
];

const modeTips={
  ffa:['В режиме «Каждый за себя» следи за подходами с обеих сторон.'],
  '1v1':['Меняй ярус, чтобы сопернику было сложнее предугадать твоё появление.'],
  '2v2':teamTips,
  '3v3':teamTips,
  train:['Тренировка с ботами приносит рейтинг и кредиты за фраги.'],
  range:[
    'На стрельбище можно испытать любое оружие из арсенала.',
    'Нажми «Освоить управление», чтобы пройти короткий учебный маршрут.',
    'Упражняйся в бросках. На стрельбище запас гранат бесконечный.'
  ],
  coop:[
    'Между волнами дронов есть пауза, чтобы восстановить здоровье.',
    'Отряду нужно пережить три волны дронов.'
  ]
};

export function pickBattleTip({mode,touch=false,bindings=defaultBindings,random=Math.random}={}){
  const key=action=>keyLabel(bindings?.[action]??defaultBindings[action]);
  const tips=controls.map(hint=>hint(touch,key));
  if(mode!=='range') tips.push(...pickups);
  if(Object.hasOwn(modeTips,mode)) tips.push(...modeTips[mode]);
  return tips[Math.floor(random()*tips.length)];
}
